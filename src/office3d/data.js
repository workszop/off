// The phase key for an hour of the day (0-23).
export function phaseForHour(hour) {
  for (const p of DAY_PHASES) {
    const inside = p.from < p.to ? hour >= p.from && hour < p.to : hour >= p.from || hour < p.to;
    if (inside) return p.key;
  }
  return 'midday';
}
